import AppKit
import UniformTypeIdentifiers

/// Reads the general pasteboard into a `PasteboardSnapshot`.
enum PasteboardReader {
    /// Markers set by password managers and utilities for content that must not be recorded.
    /// See http://nspasteboard.org.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
    ]
    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png,
        .tiff,
        .init(UTType.heic.identifier),
        .init(UTType.jpeg.identifier),
    ]
    private static let vCardType = NSPasteboard.PasteboardType(UTType.vCard.identifier)
    /// Larger texts are skipped: they would bloat the history file for little benefit.
    private static let maximumTextLength = 500_000

    static func snapshot(of pasteboard: NSPasteboard) -> PasteboardSnapshot? {
        guard let types = pasteboard.types, !types.isEmpty, ignoredTypes.isDisjoint(with: types) else { return nil }

        let fileURLs = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL]
        if let fileURLs, !fileURLs.isEmpty {
            return .files(fileURLs)
        }

        if let vCard = pasteboard.data(forType: vCardType) {
            return .contact(vCard: vCard, text: pasteboard.string(forType: .string))
        }

        if types.contains(.color), let color = NSColor(from: pasteboard), let value = ColorValue(color) {
            return .color(value)
        }

        let text = pasteboard.string(forType: .string)
        let imageData = imageTypes.lazy.compactMap { types.contains($0) ? pasteboard.data(forType: $0) : nil }.first

        // Browsers and chat apps put the image address or file name next to a copied picture:
        // the picture is what the user wants.
        if let imageData, text.map(isImageCompanionText) ?? true {
            return .image(imageData)
        }
        if let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf16.count <= maximumTextLength {
            return .text(text, rtf: pasteboard.data(forType: .rtf))
        }
        if let imageData {
            return .image(imageData)
        }
        return nil
    }

    /// Blank text, a single URL, or the file name of a picture.
    private static func isImageCompanionText(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return true }
        guard !trimmed.contains(where: \.isNewline) else { return false }

        let isSingleURL = !trimmed.contains(where: \.isWhitespace) && URL(string: trimmed)?.scheme != nil
        let isImageFileName = URL(fileURLWithPath: trimmed).isImageFile
        return isSingleURL || isImageFileName
    }
}

private extension ColorValue {
    init?(_ color: NSColor) {
        guard let rgb = color.usingColorSpace(.sRGB) else { return nil }
        self.init(red: rgb.redComponent, green: rgb.greenComponent, blue: rgb.blueComponent, alpha: rgb.alphaComponent, rawValue: "")
        // Colors from color pickers have no textual form: copying them back writes their hex code.
        self = ColorValue(red: red, green: green, blue: blue, alpha: alpha, rawValue: hexString)
    }
}
